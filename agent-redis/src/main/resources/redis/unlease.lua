--[[
摘牌 —— 释放会话执行权。

  KEYS[1] = lease   {sNNN}:sess:<sid>:lease
  KEYS[2] = inbox   {sNNN}:sess:<sid>:inbox
  KEYS[3] = cursor  {sNNN}:sess:<sid>:cursor
  ARGV[1] = 本次持有的 lease token（每次抢占唯一，INV-3）
  ARGV[2] = 游标字段名（'msg'）

返回：
   1  已摘牌      —— 确实是持有者，且 inbox 已抽干，lease 已删除
   0  仍有工作    —— 是持有者，但游标之后还有条目，lease 保留，调用方应继续 drain
  -1  非持有者    —— lease 不存在或值不是我的，什么都没做

================================================================================
为什么这三步必须在同一个脚本里（INV-2）
================================================================================
拆成客户端命令的写法是这样的：

    if inbox 已抽干 then            ← ①
        DEL lease                   ← ②
    end

①② 之间有一个缝隙。投递方在这个缝隙里执行「XADD inbox 然后 XADD ready」：
新消息进了 inbox，ready 令牌也发出去了。但令牌被谁摘到都无所谓 ——
摘到的那个 pod 会去抢 lease，而这一刻 lease 还在（②还没执行），于是它跳过；
紧接着②执行完，lease 没了，可是唤醒令牌<b>已经被消费掉了</b>。
那条消息就永远留在 inbox 里，没有任何人会再来看它一眼。

症状是"这句话机器人没理我"，Redis 没报错，日志里没异常，
下一句话进来时反而会连着上一句一起被处理 —— 于是连复现都难。

放进 Lua 之后，①② 之间不存在任何其他客户端能执行命令的时刻。
投递方要么在整个脚本之前完成（脚本看到非空，返回 0，lease 保住，drain 继续），
要么在整个脚本之后开始（lease 已经没了，它写的 ready 令牌能正常抢到执行权）。
两种排列都安全，而"中间"这个状态不存在。

================================================================================
为什么游标从 Redis 读，不由调用方传
================================================================================
调用方内存里的游标可能比 Redis 里的旧（推进失败、或者压根不是当前持有者）。
用旧游标判断会把「已处理」误判成「未处理」——那只是多转一圈，不致命；
但反过来，如果哪天改成传入更新的游标，就会把「未处理」误判成「已处理」而摘牌，
那就是丢消息。从 Redis 读是唯一不依赖调用方自律的做法。

================================================================================
槽约束（LUA-009）
================================================================================
三个 KEYS 都是同一 session 的 key，共用 {sNNN} hash tag，因此必然同槽。
全局的 ready **不传进来** —— 它刻意不分片，传进来在集群版上就是 CROSSSLOT。
--]]

local lease = redis.call('GET', KEYS[1])
if lease ~= ARGV[1] then
    -- 包含两种情况：牌子已过期被别人抢走，或者本来就没抢到。
    -- 两种都不该删 —— 删掉就是把别人的执行权摘了（INV-3）
    return -1
end

local cursor = redis.call('HGET', KEYS[3], ARGV[2])
if not cursor or cursor == false then
    cursor = '0-0'
end

-- 开区间：'(' 前缀要求 Redis 6.2+，目标版本 7.0。
-- COUNT 1 —— 只关心"有没有"，不关心有多少
local pending = redis.call('XRANGE', KEYS[2], '(' .. cursor, '+', 'COUNT', 1)
if #pending > 0 then
    return 0
end

redis.call('DEL', KEYS[1])
return 1
